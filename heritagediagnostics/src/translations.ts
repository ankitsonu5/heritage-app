// tr('pagesSelected', lang, '2', '6') fills the %s placeholders in order. Existing
// two-argument calls are unaffected.
export const tr = (key: string, lang: Lang, ...args: string[]) => {
  let text = copy[key]?.[lang === 'hi' ? 0 : 1] || key;
  for (const arg of args) text = text.replace('%s', arg);
  return text;
};
export const hasTranslation = (key: string) => Boolean(copy[key]);
